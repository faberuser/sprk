#!/usr/bin/env python3
"""Prepare the one-time immutable CI seed from an existing signed distribution."""
import argparse
import gzip
import hashlib
import io
import json
from pathlib import Path
import subprocess
import tarfile

from publish_client_update import safe_path
from client_update_bundle import verified_manifest


def prepare(updates: Path, client: Path, public_key: Path, output: Path) -> str:
    updates = updates.resolve(strict=True)
    client = client.resolve(strict=True)
    raw = (updates / "stable/manifest.json").read_bytes()
    manifest = verified_manifest(raw, public_key)
    release = updates / "releases" / manifest["version"]
    if (release / "manifest.json").read_bytes() != raw:
        raise ValueError("Stable and immutable release manifests differ")
    selected = {}
    for item in manifest["files"]:
        path = safe_path(item["path"])
        selected[path] = (release / "files" / path, item)
    patch = "King's Raid_Data/Documents/Patch/StandaloneWindows/"
    # Baked integrity metadata may reference support files that the old publisher
    # did not manage. Their expected hashes come from signed metadata files.
    for name in ("SPRK-NativeData.json", "SPRK-NativeCombat.json", "SPRK-NativeLocalization.json"):
        relative = patch + name
        if relative not in selected:
            continue
        source, item = selected[relative]
        if hashlib.sha256(source.read_bytes()).hexdigest() != item["sha256"]:
            raise ValueError("Corrupt signed native-data metadata")
        for name, info in json.loads(source.read_bytes()).get("files", {}).items():
            path = safe_path(patch + safe_path(name))
            if path not in selected:
                extra = client / path
                selected[path] = (extra, {"path": path, "size": extra.stat().st_size, "sha256": info["sha256"]})
    files = []
    for path, (source, item) in sorted(selected.items()):
        if source.resolve(strict=True) != source.absolute():
            raise ValueError(f"Symlink in seed: {path}")
        if source.stat().st_size != item["size"] or hashlib.sha256(source.read_bytes()).hexdigest() != item["sha256"]:
            raise ValueError(f"Baseline size/hash mismatch: {path}")
        files.append({"path": path, "size": item["size"], "sha256": item["sha256"]})
    metadata = json.dumps({"schema_version": 1, "previous_manifest": json.loads(raw), "files": files}, sort_keys=True).encode()
    output.parent.mkdir(parents=True, exist_ok=True)
    # Fixed gzip/tar timestamps make the seed reproducible for the same input.
    with output.open("xb") as target, gzip.GzipFile(fileobj=target, mode="wb", filename="", mtime=0) as compressed:
        with tarfile.open(fileobj=compressed, mode="w", format=tarfile.PAX_FORMAT) as archive:
            member = tarfile.TarInfo("baseline.json")
            member.size = len(metadata)
            member.mode = 0o644
            archive.addfile(member, io.BytesIO(metadata))
            for item in files:
                member = tarfile.TarInfo("files/" + item["path"])
                member.size = item["size"]
                member.mode = 0o644
                with selected[item["path"]][0].open("rb") as source:
                    archive.addfile(member, source)
    digest = hashlib.sha256()
    with output.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--updates", type=Path, default=Path("client-updates"))
    parser.add_argument("--client", type=Path, default=Path("../sprk-client"))
    parser.add_argument("--public-key", type=Path, default=Path("config/client-update-public.pem"))
    parser.add_argument("--output", type=Path, default=Path("client-updates/ci-baseline/client-baseline.tar.gz"))
    parser.add_argument("--pin-file", type=Path, default=Path(__file__).with_name("client_baseline.py"))
    parser.add_argument("--repo", default="faberuser/sprk")
    parser.add_argument("--upload", action="store_true")
    args = parser.parse_args()
    digest = prepare(args.updates, args.client, args.public_key, args.output)
    tag = "client-baseline-" + digest[:16]
    if args.upload:
        subprocess.run(["gh", "release", "create", tag, str(args.output), "--repo", args.repo, "--target", "main", "--draft", "--title", "Client CI baseline", "--notes", "Immutable distributed client build inputs; SHA-256 pinned by scripts/client_baseline.py."], check=True)
        subprocess.run(["gh", "release", "edit", tag, "--repo", args.repo, "--draft=false", "--latest=false"], check=True)
    pin = {"repository": args.repo, "tag": tag, "asset": args.output.name, "sha256": digest}
    args.pin_file.write_text('"""Fixed CI input, generated by prepare_client_baseline.py. No routine edits needed."""\n\nBASELINE = ' + json.dumps(pin, indent=4) + "\n", encoding="utf-8")
    print(f"Baseline: {args.output}; SHA-256: {digest}")
    print(f"Configured {tag}. " + ("Uploaded." if args.upload else "Upload this asset under this exact GitHub Release tag before enabling CI."))


if __name__ == "__main__":
    main()
