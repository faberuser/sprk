-- battle::migrate and battle::seasons.

CREATE TABLE challenge_results (
    season bigint NOT NULL,
    challenge bigint NOT NULL,
    account bigint NOT NULL,
    score bigint NOT NULL,
    battle_time bigint NOT NULL,
    current_score bigint NOT NULL,
    "current_time" bigint NOT NULL,
    PRIMARY KEY (season, challenge, account)
);

CREATE TABLE challenge_teams (
    season bigint NOT NULL,
    challenge bigint NOT NULL,
    -- JSON array of account IDs; part of the key.
    team text NOT NULL,
    score bigint NOT NULL,
    battle_time bigint NOT NULL,
    data text NOT NULL,
    PRIMARY KEY (season, challenge, team)
);

-- data holds JSON objects, arrays or the JSON scalar null depending on kind.
CREATE TABLE battle_state (
    account bigint NOT NULL,
    kind text NOT NULL,
    idx bigint NOT NULL,
    data text NOT NULL,
    PRIMARY KEY (account, kind, idx)
) WITH (fillfactor = 85);
-- Dispatch runs still waiting for simulation results. Queries must repeat
-- this predicate exactly for the planner to use the index.
CREATE INDEX battle_state_dispatch_pending ON battle_state (account, idx)
    WHERE kind = 'dispatch'
      AND sprk_json_int(data, '$.SimulationVersion') IN (1, 2)
      AND sprk_json_text(data, '$.State') NOT IN ('Complete', 'Cancel')
      AND COALESCE(sprk_json_array_length(data, '$.SimulationResults'), 0) < sprk_json_int(data, '$.RepeatCount');

CREATE TABLE battle_runs (
    account bigint PRIMARY KEY,
    run_id text NOT NULL,
    started bigint NOT NULL,
    completed bigint NOT NULL DEFAULT 0,
    entry text NOT NULL,
    begin_response text NOT NULL
);

CREATE TABLE battle_rooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family text NOT NULL,
    master bigint NOT NULL,
    data text NOT NULL,
    updated bigint NOT NULL
);

CREATE TABLE battle_room_members (
    account bigint PRIMARY KEY,
    room bigint NOT NULL REFERENCES battle_rooms(id) ON DELETE CASCADE,
    joined bigint NOT NULL,
    updated bigint NOT NULL
);

CREATE TABLE battle_scores (
    family text NOT NULL,
    boss bigint NOT NULL,
    season bigint NOT NULL,
    account bigint NOT NULL,
    day text NOT NULL,
    score bigint NOT NULL,
    battle_time bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (family, boss, season, account, day)
);

CREATE TABLE battle_reward_claims (
    account bigint NOT NULL,
    kind text NOT NULL,
    idx bigint NOT NULL,
    period text NOT NULL,
    PRIMARY KEY (account, kind, idx, period)
);

-- Range guard replaces SQLite's currency64_battle_* triggers.
CREATE TABLE battle_currencies (
    account bigint NOT NULL,
    kind text NOT NULL,
    value bigint NOT NULL DEFAULT 0 CONSTRAINT battle_currencies_nonnegative CHECK (value >= 0),
    PRIMARY KEY (account, kind)
);

CREATE TABLE eclipse_run_ids (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account bigint NOT NULL
);

CREATE TABLE battle_entry_holds (
    account bigint NOT NULL,
    owner text NOT NULL,
    family text NOT NULL,
    kind bigint NOT NULL,
    amount bigint NOT NULL CHECK (amount > 0),
    expires bigint NOT NULL,
    PRIMARY KEY (account, owner, family, kind)
);

CREATE TABLE world_boss_legacy_scores (
    boss bigint NOT NULL,
    season bigint NOT NULL,
    account bigint NOT NULL,
    day text NOT NULL,
    score bigint NOT NULL,
    battle_time bigint NOT NULL,
    PRIMARY KEY (boss, season, account, day)
);
