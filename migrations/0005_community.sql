-- community::migrate (guilds, arena, duels).

CREATE TABLE community_state (
    owner bigint NOT NULL,
    kind text NOT NULL,
    idx bigint NOT NULL,
    data jsonb NOT NULL,
    PRIMARY KEY (owner, kind, idx)
);

CREATE TABLE community_claims (
    account bigint NOT NULL,
    kind text NOT NULL,
    target bigint NOT NULL,
    period text NOT NULL,
    PRIMARY KEY (account, kind, target, period)
);

CREATE TABLE guild_requests (
    account bigint NOT NULL,
    guild_id bigint NOT NULL REFERENCES guilds(guild_id) ON DELETE CASCADE,
    created bigint NOT NULL,
    PRIMARY KEY (account, guild_id)
);

-- season, nonduel and squad are derived from data and mission_summary is a
-- digest of data, all maintained by arena_runs_derive (0008). They are 0/1
-- or NULL like the SQLite columns.
CREATE TABLE arena_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account bigint NOT NULL,
    kind bigint NOT NULL,
    started bigint NOT NULL,
    status text NOT NULL,
    data jsonb NOT NULL,
    mission_summary jsonb,
    season bigint,
    nonduel bigint,
    squad bigint,
    last_poll bigint
);
CREATE UNIQUE INDEX arena_active_account ON arena_runs (account) WHERE status IN ('waiting', 'battle');
-- SQLite indexed json_extract(data,'$.Season'); the season column holds the
-- same value, so ported queries should filter on season.
CREATE INDEX arena_completed_squad ON arena_runs (account, kind, season, id DESC) WHERE status = 'complete';
CREATE INDEX arena_mission_history ON arena_runs (account, status, id, kind, started) INCLUDE (mission_summary) WHERE status = 'complete';
CREATE INDEX arena_online_match_status ON arena_runs (sprk_json_int(data -> 'OnlineMatchUid'), status)
    WHERE sprk_json_int(data -> 'OnlineMatchUid') IS NOT NULL;
CREATE INDEX arena_retention ON arena_runs (account, kind, id, status, season, nonduel, squad);
CREATE INDEX arena_waiting_queue ON arena_runs (kind, started) WHERE status = 'waiting';

CREATE TABLE arena_snapshots (
    run bigint PRIMARY KEY,
    data jsonb NOT NULL
);

CREATE TABLE arena_scores (
    account bigint NOT NULL,
    kind bigint NOT NULL,
    season bigint NOT NULL,
    score bigint NOT NULL,
    wins bigint NOT NULL DEFAULT 0,
    losses bigint NOT NULL DEFAULT 0,
    data jsonb NOT NULL DEFAULT '{}',
    PRIMARY KEY (account, kind, season)
);

CREATE TABLE guild_battle_scores (
    guild_id bigint NOT NULL,
    account bigint NOT NULL,
    kind text NOT NULL,
    season bigint NOT NULL,
    stage bigint NOT NULL,
    score bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (guild_id, account, kind, season, stage)
);
CREATE INDEX guild_battle_scores_account_kind ON guild_battle_scores (account, kind);

CREATE TABLE guild_arena_decks (
    guild_id bigint NOT NULL,
    account bigint NOT NULL,
    season bigint NOT NULL,
    deck bigint NOT NULL,
    data jsonb NOT NULL,
    PRIMARY KEY (account, season, deck)
);

CREATE TABLE friendly_duels (
    group_id bigint PRIMARY KEY,
    requester bigint NOT NULL,
    opponent bigint NOT NULL,
    status text NOT NULL,
    expires bigint NOT NULL
);

CREATE TABLE guild_arena_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guild_id bigint NOT NULL,
    enemy_guild bigint NOT NULL,
    account bigint NOT NULL,
    enemy bigint NOT NULL,
    season bigint NOT NULL,
    win bigint NOT NULL,
    data jsonb NOT NULL
);
