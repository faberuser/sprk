-- Core player tables (database::create_tables), auth, coupons and client
-- storage reports. Column names, keys and defaults match the SQLite schema.

CREATE TABLE accounts (
    account_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id text NOT NULL UNIQUE,
    login_method bigint NOT NULL DEFAULT 0,
    device_id text,
    nick text,
    created_at text NOT NULL DEFAULT sprk_now(),
    last_login text,
    session_key text,
    aes_key text,
    country_code text DEFAULT 'US',
    is_banned bigint NOT NULL DEFAULT 0,
    last_logout text
);

-- Currency guards replace SQLite's currency64_user_* triggers: bigint already
-- rejects non-integers and overflow, so only the ranges remain.
CREATE TABLE user_info (
    account_id bigint PRIMARY KEY REFERENCES accounts(account_id),
    gold bigint NOT NULL DEFAULT 0,
    gem bigint NOT NULL DEFAULT 0,
    pay_gem bigint NOT NULL DEFAULT 0,
    pvp_coin bigint NOT NULL DEFAULT 0,
    stamina bigint NOT NULL DEFAULT 200,
    stamina_recharge_time bigint NOT NULL DEFAULT 0,
    team_level bigint NOT NULL DEFAULT 1,
    team_exp bigint NOT NULL DEFAULT 0,
    sword bigint NOT NULL DEFAULT 5,
    sword_recharge_time bigint NOT NULL DEFAULT 0,
    sword2 bigint NOT NULL DEFAULT 0,
    avatar_hero_index bigint NOT NULL DEFAULT 0,
    royal_point bigint NOT NULL DEFAULT 0,
    raid_point bigint NOT NULL DEFAULT 0,
    mileage bigint NOT NULL DEFAULT 0,
    friendship_point bigint NOT NULL DEFAULT 0,
    guild_raid_ticket bigint NOT NULL DEFAULT 0,
    world_boss_ticket bigint NOT NULL DEFAULT 0,
    event_dungeon_point bigint NOT NULL DEFAULT 0,
    CONSTRAINT user_info_currency_nonnegative CHECK (
        gold >= 0 AND gem >= 0 AND pay_gem >= 0 AND pvp_coin >= 0 AND stamina >= 0
        AND sword >= 0 AND sword2 >= 0 AND royal_point >= 0 AND raid_point >= 0
        AND event_dungeon_point >= 0 AND mileage >= 0 AND friendship_point >= 0
        AND guild_raid_ticket >= 0 AND world_boss_ticket >= 0),
    CONSTRAINT user_info_gem_total_fits CHECK (gem <= 9223372036854775807 - pay_gem)
) WITH (fillfactor = 85);

