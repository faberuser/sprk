	public ResultType Check(string nick)
	{
		if (string.IsNullOrEmpty(nick))
		{
			return ResultType.EmptyNick;
		}
		int valueInt = GameRoot.Instance.ConstantDataContainer.GetValueInt("MinNickLength");
		int valueInt2 = GameRoot.Instance.ConstantDataContainer.GetValueInt("MaxNickLength");
		if (nick.Length < valueInt)
		{
			return ResultType.TooShortNick;
		}
		if (nick.Length > valueInt2)
		{
			return ResultType.TooLongNick;
		}
		if (!ServerLanguageChecker.CheckValidCharacter(nick))
		{
			return ResultType.InvalidNickInThisServer;
		}
		switch (GameRoot.Instance.CensoredWordDataContainer.IsCensoredWord(nick))
		{
		case CensoredWordDataContainer.CensoredResult.Censored:
			return ResultType.CensoredWord;
		case CensoredWordDataContainer.CensoredResult.Sensitive:
			return ResultType.SensitiveWord;
		default:
			if (!CheckValidCharacter(nick))
			{
				return ResultType.InvalidNick;
			}
			if (CheckSimilarWord(nick))
			{
				return ResultType.InvalidNick;
			}
			return ResultType.Success;
		}
	}

	public static bool CheckSimilarWord(string nick)
	{
		IList<CensoredWordData> similarCheckWordList = GameRoot.Instance.CensoredWordDataContainer.GetSimilarCheckWordList();
		if (similarCheckWordList == null)
		{
			return false;
		}
		foreach (CensoredWordData item in similarCheckWordList)
		{
			if (GameRoot.Instance.SimilarAlphabetDataContainer.IsSimilarWordCheck(nick, item.Word, isIncludeCheck: true))
			{
				return true;
			}
		}
		return false;
	}
