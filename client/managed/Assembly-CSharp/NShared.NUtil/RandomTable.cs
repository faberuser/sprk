	private readonly SnapshotObjectMember<BattleCreature> _ownerHolder;

	private readonly SnapshotObjectMember<int> _indexHolder;

	public RandomTable()
	{
		_ownerHolder = new SnapshotObjectMember<BattleCreature>(this);
		_indexHolder = new SnapshotObjectMember<int>(this, 0);
	}

	public void Init(BattleCreature owner, int index)
	{
		_ownerHolder.Set(owner);
		InitIndex(index);
	}

	public void Init(int index)
	{
		InitIndex(index);
	}

	private void InitIndex(int index)
	{
		_indexHolder.Set(index % RandomNumbers.Length);
	}

	public int GetIndex()
	{
		return _indexHolder.Get();
	}

	public int NextRandom(string desc)
	{
		int index = GetIndex();
		int result = RandomNumbers[index];
		int index2 = (index + 1) % RandomNumbers.Length;
		InitIndex(index2);
		if (_ownerHolder.Get() != null)
		{
			_ownerHolder.Get().BattleInstance.TraceBattleEvent(false, "RANDOM", desc);
		}
		return result;
	}

	public int NextRandom(int max, string desc)
	{
		int num = NextRandom(desc);
		return (int)((long)max * (long)num / 1000);
	}

	public int NextRandom(int min, int max, string desc)
	{
		int num = NextRandom(desc);
		return min + (int)((long)(max - min) * (long)num / 1000);
	}

	public static int GetRandomByMonth(int monthFromMillennium, int salt)
	{
		int num = Math.Max(monthFromMillennium + salt, 0) % RandomNumbers.Length;
		return RandomNumbers[num];
	}
