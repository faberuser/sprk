	private static StreamWriter CreateWriter_for_Split_MessagePack(string originalPath, string generated_dir, int writerIndex, Encoding encoding)
	{
		if (!Directory.Exists(generated_dir))
		{
			Directory.CreateDirectory(generated_dir);
		}
