"""Validate SPRK translations and generate the shared managed catalog."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'localization/sprk.tsv'
OUTPUT = ROOT / 'managed/Assembly-CSharp/SprkText.Generated.cs'
LANGUAGES = ['German', 'French', 'Japanese', 'Korean', 'Russian', 'ChineseSimplified', 'ChineseTraditional']


def read_entries(source=SOURCE):
    entries = {}
    for number, line in enumerate(source.read_text(encoding='utf-8').splitlines(), 1):
        if not line or line.startswith('#'):
            continue
        cells = [s.replace('\\n', '\n') for s in line.split('\t')]
        if len(cells) != 8 or any(not s.strip() for s in cells):
            raise ValueError(f'{SOURCE.name}:{number}: expected English and seven nonempty translations')
        key, *values = cells
        if any('\ufffd' in value or re.search(r'\?{2,}', value) for value in values):
            raise ValueError(f'{SOURCE.name}:{number}: possible text encoding damage')
        if key in entries:
            raise ValueError(f'Duplicate key: {key}')
        for language, value in zip(LANGUAGES, values):
            for pattern in (r'\{\d+(?:[^{}]*)\}', r'\[(?:/?[a-zA-Z]+|[0-9a-fA-F]{6}|-)\]'):
                if sorted(re.findall(pattern, key)) != sorted(re.findall(pattern, value)):
                    raise ValueError(f'{language}: mismatched formatting: {key}')
        entries[key] = values
    return entries


def generate():
    entries = read_entries()
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    lines = ['// Generated by client/scripts/build/build_sprk_localization.py; edit client/localization/sprk.tsv.',
             'using System.Collections.Generic;', '', 'public static partial class SprkText', '{',
             '\tprivate static readonly string[] Languages = { ' + ', '.join(map(quote, LANGUAGES)) + ' };',
             '\tprivate static readonly Dictionary<string, string[]> Translations = new Dictionary<string, string[]>', '\t{']
    for key, values in entries.items():
        lines.append('\t\t{ ' + quote(key) + ', new string[] { ' + ', '.join(map(quote, values)) + ' } },')
    lines.extend(['\t};', '}', ''])
    return '\n'.join(lines), len(entries)


def check():
    content, count = generate()
    if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != content:
        raise ValueError('Generated SPRK catalog is stale; run client/scripts/build/build_sprk_localization.py.')
    return count


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count = generate()
    if args.check:
        check()
    else:
        OUTPUT.write_text(content, encoding='utf-8')
    print(f'Validated {count} strings in {len(LANGUAGES)} non-English languages.')
