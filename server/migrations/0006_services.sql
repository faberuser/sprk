-- services::migrate (replays, ranking decks, internal service results).

CREATE TABLE service_replays (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner bigint NOT NULL,
    kind bigint NOT NULL,
    info text NOT NULL,
    -- base64 replay payload, not JSON.
    data text NOT NULL,
    created bigint NOT NULL
);

CREATE TABLE service_replay_accounts (
    replay bigint NOT NULL REFERENCES service_replays(id) ON DELETE CASCADE,
    account bigint NOT NULL,
    PRIMARY KEY (replay, account)
);
CREATE INDEX service_replay_account ON service_replay_accounts (account, replay);

CREATE TABLE service_decks (
    account bigint NOT NULL,
    chapter bigint NOT NULL,
    dungeon bigint NOT NULL,
    difficulty bigint NOT NULL,
    kind bigint NOT NULL,
    metric bigint NOT NULL,
    data text NOT NULL,
    PRIMARY KEY (account, chapter, dungeon, difficulty, kind)
);
CREATE INDEX service_deck_rank ON service_decks (chapter, dungeon, difficulty, kind, metric, account);

CREATE TABLE service_results (
    run text PRIMARY KEY,
    account bigint NOT NULL,
    request text NOT NULL,
    response text NOT NULL,
    created bigint NOT NULL
);

CREATE TABLE service_servers (
    name text PRIMARY KEY,
    data text NOT NULL,
    seen bigint NOT NULL
);

CREATE TABLE service_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL,
    data text NOT NULL,
    created bigint NOT NULL
);
