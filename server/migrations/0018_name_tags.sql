-- account::name_tag: Discord-style name tags (a small icon and a short text
-- in a coloured pill) shown after a player's name on every screen and in chat.
-- Tags are created, edited, deleted and assigned only by GM (gm.py name-tag).
--
-- Every server query that shows a player's name selects
-- sprk_display_nick(account_id, nick): the nick prefixed with an invisible
-- marker U+E0A0 <tag id> U+E0A1 when the player has a tag. The client
-- (SprkNameTag) removes the marker from the label and draws the badge.
-- Name searches, validation and storage keep using the raw accounts.nick.
CREATE TABLE name_tags (
    tag_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- GM handle used by gm.py, e.g. "wao" (lowercase letters, digits, - and _).
    name text NOT NULL UNIQUE,
    -- Text shown in the pill, e.g. "WAO".
    label text NOT NULL,
    -- RRGGBB hex colours.
    text_color text NOT NULL DEFAULT 'FFFFFF',
    background_color text NOT NULL DEFAULT '2B2D31',
    -- Optional small PNG icon shown before the text.
    icon bytea,
    updated_at text NOT NULL DEFAULT sprk_now()
);

-- One tag per player, like a Discord server tag.
CREATE TABLE account_name_tags (
    account_id bigint PRIMARY KEY REFERENCES accounts(account_id) ON DELETE CASCADE,
    tag_id bigint NOT NULL REFERENCES name_tags(tag_id) ON DELETE CASCADE,
    assigned_at text NOT NULL DEFAULT sprk_now()
);
CREATE INDEX account_name_tags_tag ON account_name_tags(tag_id);

-- 57504 = U+E0A0, 57505 = U+E0A1 (private use; stripped from player input).
CREATE FUNCTION sprk_display_nick(p_account bigint, p_nick text) RETURNS text
LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN p_nick IS NULL OR p_nick = '' THEN p_nick
        ELSE COALESCE((SELECT chr(57504) || t.tag_id::text || chr(57505)
                       FROM account_name_tags t WHERE t.account_id = p_account), '') || p_nick
    END
$$;
